#!/usr/bin/env python3
"""Compile maintainable HTML sources in src/web_src/ into deterministic gzipped
PROGMEM C headers (src/webMonitorPage.h and src/webOtaPage.h)."""

import gzip
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PAGES = [
    {
        "src": ROOT / "src" / "web_src" / "monitor.html",
        "dst": ROOT / "src" / "webMonitorPage.h",
        "guard": "WEB_MONITOR_PAGE_H",
        "sym": "MONITOR_HTML_GZ",
        "desc": "Live miner monitor & LAN fleet dashboard served at '/' (Content-Encoding: gzip).",
    },
    {
        "src": ROOT / "src" / "web_src" / "ota.html",
        "dst": ROOT / "src" / "webOtaPage.h",
        "guard": "WEB_OTA_PAGE_H",
        "sym": "OTA_HTML_GZ",
        "desc": "OTA firmware update UI served at '/update' (Content-Encoding: gzip).",
    },
]


def compact_html(src_text: str) -> bytes:
    """Strip safe line indentation and standalone comment lines while keeping
    maintainable formatting in src/web_src/*.html untouched."""
    src_text = re.sub(r"<!--.*?-->", "", src_text, flags=re.DOTALL)
    out_lines = []
    for raw_line in src_text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("//"):
            continue
        if line.startswith("/*") and line.endswith("*/"):
            continue
        out_lines.append(line)
    return ("\n".join(out_lines) + "\n").encode("utf-8")


def format_c_array(data: bytes, per_line: int = 16) -> str:
    lines = []
    for idx in range(0, len(data), per_line):
        chunk = data[idx : idx + per_line]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk))
    return ",\n".join(lines)


def build_header(spec: dict) -> tuple[int, int, int]:
    raw_text = spec["src"].read_text(encoding="utf-8")
    raw_len = len(raw_text.encode("utf-8"))
    compact_bytes = compact_html(raw_text)
    gz_bytes = gzip.compress(compact_bytes, compresslevel=9, mtime=0)
    rel_src = spec["src"].relative_to(ROOT).as_posix()

    header = (
        f"#ifndef {spec['guard']}\n"
        f"#define {spec['guard']}\n\n"
        f"// AUTO-GENERATED by tools/gen_web_pages.py from {rel_src} -- DO NOT EDIT DIRECTLY.\n"
        f"// {spec['desc']}\n"
        f"// Source: {raw_len} B -> Compact: {len(compact_bytes)} B -> Gzipped: {len(gz_bytes)} B\n\n"
        f"#include <Arduino.h>\n"
        f"#include <stddef.h>\n"
        f"#include <stdint.h>\n\n"
        f"static const size_t {spec['sym']}_LEN = {len(gz_bytes)}U;\n"
        f"static const uint8_t {spec['sym']}[] PROGMEM = {{\n"
        f"{format_c_array(gz_bytes)}\n"
        f"}};\n\n"
        f"#endif // {spec['guard']}\n"
    )
    spec["dst"].write_text(header, encoding="utf-8")
    return raw_len, len(compact_bytes), len(gz_bytes)


def main() -> None:
    for spec in PAGES:
        raw_len, cmp_len, gz_len = build_header(spec)
        ratio = (1.0 - (gz_len / raw_len)) * 100.0 if raw_len else 0.0
        print(
            f"[gen_web_pages] {spec['src'].relative_to(ROOT)} -> {spec['dst'].relative_to(ROOT)}: "
            f"{raw_len} B raw ({cmp_len} B compact) -> {gz_len} B gz ({ratio:.1f}% saved)"
        )


if __name__ == "__main__":
    main()
